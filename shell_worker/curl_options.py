def blocked_reason(name: str) -> str | None:
    """返回拦截理由；``None`` 表示放行。"""
    reason = BLOCKED.get(name)
    if reason:
        return reason
    if name.startswith(_BLOCKED_PREFIX):
        return f"不允许改连接路径或解析方式（{name}）"
    return None

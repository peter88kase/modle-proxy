"""curl 参数总表 + 危险能力黑名单。

为什么不是白名单
----------------
早期实现只允许 ``-X/-H/-d/-u/-b/-A/-e/-m/-w`` 等十来个参数，理由是"最安全"。
代价是**任何从文档 / Postman / 浏览器复制出来的真实命令都会被拒**——最常见的
``curl --location --request POST ...`` 直接报 ``参数 --location 未获授权``。
一个诊断工具连真实命令都粘贴不进去，安全就没有意义：用户会绕开平台去手工执行。

现在改成「能力黑名单」：默认放行 curl 的全部参数形态，只拦下那些会**扩大攻击面**
的能力，并且拦截时给出人话理由，而不是一句"未获授权"。

被拦的只有五类
--------------
1. 写盘 / 读配置：``-o/-O/-D/-c/-K``、``--trace*``、``--libcurl``、``--etag-save``、
   ``--hsts``、``--alt-svc``。诊断输出就该回到页面，不该在服务器上留文件。
2. 把服务器文件塞进请求体：``-T``、``-F``（含 ``@``）、``--netrc*``、``-d @file``。
   这是唯一能把 worker 本机文件发出去的外带通道，必须堵死。
3. 改目标地址 / 绕开 IP 固定：``--resolve``、``--connect-to``、``--unix-socket``、
   ``--interface``、``-x/--proxy*``、``--socks*``、``--doh-*``、``--dns-*``。
4. 平台自己掌管的全局开关：``--max-redirs``、``--proto``、``--proto-redir``、
   ``--location-trusted``（会把 Authorization 带到重定向目标）。
5. 一次跑多条请求：``--next``、``-Z/--parallel*``、``-q/--disable``（必须是首参）。

``-L/--location`` 是放行的，重定向次数由平台钳制（见 ``worker.parse_raw_curl``），
并且最终 URL 会被记录下来，跨主机跳转在结果里可见。
"""

